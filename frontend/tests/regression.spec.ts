test('ten-question practice retains state and scores revealed, wrong and unanswered responses correctly', async ({ page, mockApi }, testInfo) => {
  await openDocument(page)
  await openQuiz(page)
  await page.getByRole('button', { name: 'Start 10 questions' }).click()
  const quiz = page.locator('.quiz-panel')
  await expect(quiz.getByRole('navigation', { name: 'Quiz questions' }).getByRole('button')).toHaveCount(10)
  await quiz.getByRole('radio').nth(0).check()
  await expect(quiz.getByRole('radio').nth(0)).toBeChecked()
  await quiz.getByRole('button', { name: 'Show answer', exact: true }).click()
  const reveal = page.getByRole('dialog', { name: 'See the reasoning first?' })
  await expect(reveal).toContainText('even if your selected answer is correct')
  await reveal.getByRole('button', { name: 'Reveal answer', exact: true }).click()
  await expect(quiz.getByRole('radio').nth(0)).toBeDisabled()
  await expect(quiz.getByRole('button', { name: 'Question 1: Revealed, no credit', exact: true })).toBeVisible()
  await quiz.getByRole('button', { name: 'Next', exact: true }).click()
  await quiz.getByRole('radio').nth(0).check()
  await quiz.getByRole('button', { name: 'Next', exact: true }).click()
  await quiz.getByRole('radio').nth(1).check()
  await expect(quiz.locator('.quiz-progress-copy')).toContainText('3 / 10 answered')
  if (page.viewportSize()!.width <= 900) await page.getByRole('button', { name: 'Close study tools', exact: true }).click()
  else await page.getByRole('button', { name: 'Hide tools', exact: true }).click()
  await expect(quiz).not.toBeVisible()
  await reopenQuiz(page)
  await expect(quiz.getByRole('button', { name: 'Question 3: Answered', exact: true })).toHaveAttribute('aria-current', 'step')
  await expect(quiz.getByRole('radio').nth(1)).toBeChecked()
  await page.locator('.tabs').getByRole('button', { name: 'Text', exact: true }).click()
  await page.locator('.tabs').getByRole('button', { name: 'Check Me', exact: true }).click()
  await expect(quiz.getByRole('radio').nth(1)).toBeChecked()
  expect(mockApi.callsFor('POST', '/documents/1/quiz')).toHaveLength(1)
  await quiz.getByRole('button', { name: 'Submit practice' }).click()
  const submit = page.getByRole('dialog', { name: 'Submit with unanswered questions?' })
  await expect(submit).toContainText('7 questions are unanswered')
  await submit.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(quiz.locator('.quiz-progress-copy')).toContainText('3 / 10 answered')
  await quiz.getByRole('button', { name: 'Submit practice' }).click()
  await submit.getByRole('button', { name: 'Submit anyway', exact: true }).click()
  await expect(quiz.locator('.quiz-progress-copy')).toContainText('1 / 10 earned')
  await expect(quiz.getByRole('progressbar', { name: 'Earned score' })).toHaveAttribute('value', '1')
  await expect(quiz.getByRole('button', { name: 'Question 1: Revealed, no credit', exact: true })).toBeVisible()
  await expect(quiz.getByRole('button', { name: 'Question 2: Correct', exact: true })).toBeVisible()
  await expect(quiz.getByRole('button', { name: 'Question 3: Needs revision', exact: true })).toBeVisible()
  await quiz.getByRole('button', { name: 'Question 4: Unanswered', exact: true }).click()
  await expect(quiz.getByRole('radio').nth(0)).toBeDisabled()
  await expect(quiz.getByRole('heading', { name: 'Why this answer works' })).toBeAttached()
  await screenshot(page, testInfo, 'quiz-incomplete-review')
})

