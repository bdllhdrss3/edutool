test('chat keeps its composer fixed; Shift+Enter inserts a newline and Enter sends once', async ({ page, mockApi }, testInfo) => {
  await showNavigation(page)
  await page.locator('.chat-history-row').getByRole('button', { name: chatTitle, exact: true }).click()
  await expect(page.locator('.messages .message')).toHaveCount(16)
  await scrollInnerKeepingChrome(page, page.locator('.messages'), [page.locator('.chat-content .head'), page.locator('.composer')])
  const input = page.getByRole('textbox', { name: 'Message about this document', exact: true })
  await input.fill('First line')
  await input.press('Shift+Enter')
  await expect(input).toHaveValue('First line\n')
  expect(mockApi.callsFor('POST', '/chat')).toHaveLength(0)
  await input.press('x')
  await input.press('Enter')
  await expect(page.locator('.messages .message')).toHaveCount(18)
  await expect(input).toHaveValue('')
  expect(mockApi.callsFor('POST', '/chat').map(call => call.body)).toEqual([
    { content: 'First line\nx', document_id: 1, conversation_id: 11 },
  ])
  await expect(page.locator('.message.assistant').last()).toHaveText('Mock reply: First line\nx')
  await expect(page.getByRole('button', { name: 'Send message', exact: true })).toBeDisabled()
  await input.press('Enter')
  await expect(input).toHaveValue('')
  expect(mockApi.callsFor('POST', '/chat')).toHaveLength(1)
  await noBodyOverflow(page)
  await screenshot(page, testInfo, 'chat-multiline-send')
})