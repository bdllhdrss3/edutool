test('library actions align with their rows and the body stays within the viewport', async ({ page }, testInfo) => {
  await noBodyOverflow(page)
  await inViewport(page.locator('.library-actions'), page)
  const clear = await box(page.getByRole('button', { name: 'Clear library', exact: true }))
  const upload = await box(page.locator('.library-upload'))
  // Both actions may wrap as a group on narrow screens, but never overlap.
  expect(clear.x + clear.width <= upload.x + 1 || clear.y + clear.height <= upload.y + 1).toBeTruthy()
  const rightEdges: number[] = []
  for (const row of await page.locator('.library-item').all()) {
    const content = await box(row.locator('.library-row'))
    const action = await box(row.locator('.library-delete'))
    await inViewport(row.locator('.library-delete'), page)
    expect(action.x).toBeGreaterThanOrEqual(content.x + content.width)
    expect(Math.abs(action.y + action.height / 2 - content.y - content.height / 2)).toBeLessThanOrEqual(1)
    rightEdges.push(action.x + action.width)
  }
  expect(Math.abs(rightEdges[0]! - rightEdges[1]!)).toBeLessThanOrEqual(1)
  await screenshot(page, testInfo, 'library-alignment')
})

test('chat options support right-click, visible ellipsis, keyboard navigation and Escape focus', async ({ page }, testInfo) => {
  await showNavigation(page)
  const trigger = page.getByRole('button', { name: `Options for ${chatTitle}`, exact: true })
  await inViewport(trigger, page)
  await expect(trigger).toHaveCSS('opacity', '1')
  await expect(trigger.locator('svg')).toBeVisible()
  await page.locator('.chat-history-row').filter({ hasText: chatTitle }).click({ button: 'right' })
  const menu = page.getByRole('dialog', { name: 'Saved chat options' })
  await inViewport(menu, page)
  await expect(page.getByRole('menuitem', { name: 'Open chat', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Delete chat', exact: true })).toBeFocused()
  await screenshot(page, testInfo, 'chat-context-menu')
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await trigger.press('Shift+F10')
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('failed DELETE closes confirmation and shows a dismissible floating snackbar', async ({ page, mockApi }, testInfo) => {
  mockApi.failDeletes = true
  await showNavigation(page)
  const trigger = page.getByRole('button', { name: `Options for ${chatTitle}`, exact: true })
  await trigger.click()
  await page.getByRole('menuitem', { name: 'Delete chat', exact: true }).click()
  const dialog = page.getByRole('alertdialog', { name: 'Delete this chat?' })
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  expect(mockApi.callsFor('DELETE', '/conversations/11')).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Delete chat', exact: true }).click()
  const error = page.getByRole('alert')
  await expect(error).toContainText('Mock deletion failed. Nothing was removed.')
  await expect(dialog).not.toBeVisible()
  await inViewport(error, page)
  expect(await page.locator('.toast-stack').evaluate(element => element.matches(':popover-open'))).toBe(true)
  const dismiss = page.getByRole('button', { name: 'Dismiss error', exact: true })
  await screenshot(page, testInfo, 'delete-error-over-modal')
  await dismiss.click()
  await expect(error).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await expect(page.locator('.chat-history-row')).toHaveCount(3)
  expect(mockApi.callsFor('DELETE', '/conversations/11')).toHaveLength(1)
  expect(mockApi.conversations).toHaveLength(3)
})

for (const kind of ['chat', 'document', 'history', 'library'] as const) {
  test(`successful mocked ${kind} cleanup removes only the intended data`, async ({ page, mockApi }) => {
    const settings = {
      chat: { path: '/conversations/11', title: 'Delete this chat?', action: 'Delete chat', notice: 'Chat deleted.', docs: 2, chats: 2 },
      document: { path: '/documents/1', title: 'Delete this PDF?', action: 'Delete PDF', notice: 'PDF deleted.', docs: 1, chats: 1 },
      history: { path: '/conversations', title: 'Clear chat history?', action: 'Clear history', notice: 'Chat history cleared.', docs: 2, chats: 0 },
      library: { path: '/documents', title: 'Clear your library?', action: 'Clear library', notice: 'Library cleared.', docs: 0, chats: 0 },
    }[kind]
    // Delete the active conversation/history as well as checking saved lists.
    if (kind === 'chat' || kind === 'history') {
      await showNavigation(page)
      await page.locator('.chat-history-row').getByRole('button', { name: chatTitle, exact: true }).click()
      await expect(page.locator('.messages .message')).toHaveCount(16)
      if (isPhone(page)) await page.getByRole('button', { name: 'Close study tools', exact: true }).click()
      await showNavigation(page)
      if (kind === 'chat') {
        await page.getByRole('button', { name: `Options for ${chatTitle}`, exact: true }).click()
        await page.getByRole('menuitem', { name: 'Delete chat', exact: true }).click()
      } else await page.getByRole('button', { name: 'Clear chat history', exact: true }).click()
    } else if (kind === 'document') await page.getByRole('button', { name: `Delete ${documentTitle}`, exact: true }).click()
    else await page.getByRole('button', { name: 'Clear library', exact: true }).click()
    const dialog = page.getByRole('alertdialog', { name: settings.title })
    await expect(dialog).toBeVisible()
    expect(mockApi.callsFor('DELETE', settings.path)).toHaveLength(0)
    await dialog.getByRole('button', { name: settings.action, exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.locator('.notice-toast')).toContainText(settings.notice)
    await expect(page.locator('.chat-history-row')).toHaveCount(settings.chats)
    expect(mockApi.callsFor('DELETE', settings.path)).toHaveLength(1)
    expect(mockApi.documents).toHaveLength(settings.docs)
    expect(mockApi.conversations).toHaveLength(settings.chats)
    if (kind === 'chat' || kind === 'history') {
      await hideNavigation(page)
      if (isPhone(page)) await page.getByRole('button', { name: 'Open study tools', exact: true }).click()
      await expect(page.locator('.messages .message')).toHaveCount(0)
      await expect(page.locator('.chat-empty')).toBeVisible()
      if (isPhone(page)) await page.getByRole('button', { name: 'Close study tools', exact: true }).click()
      await page.getByRole('button', { name: 'Back to My library', exact: true }).click()
    }
    await expect(page.locator('.library-item')).toHaveCount(settings.docs)
    if (kind === 'document') await expect(page.locator('.library-row')).toContainText('Networks and distributed systems')
    if (kind === 'library') await expect(page.getByRole('heading', { name: 'No PDFs yet' })).toBeVisible()
    // A fresh UI load still reflects the mutable mock store, not stale Vue state.
    await page.reload()
    await expect(page.getByRole('heading', { name: 'My library', exact: true })).toBeVisible()
    await expect(page.locator('.library-item')).toHaveCount(settings.docs)
    await expect(page.locator('.chat-history-row')).toHaveCount(settings.chats)
  })
}

